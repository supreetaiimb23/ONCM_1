-- ---------------------------------------------------------------------------------------------------------------------
-- 7. updated_at maintenance
-- ---------------------------------------------------------------------------------------------------------------------
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end $$;

drop trigger if exists trg_organizations_touch on public.organizations;
create trigger trg_organizations_touch before update on public.organizations
    for each row execute function public.touch_updated_at();

drop trigger if exists trg_documents_touch on public.documents;
create trigger trg_documents_touch before update on public.documents
    for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------------------------------------------------
-- 8. Lock down the public Supabase API (RLS on, no policies = deny all for anon / authenticated)
-- ---------------------------------------------------------------------------------------------------------------------
do $$
declare t text;
begin
    foreach t in array array[
        'profiles', 'organizations', 'join_requests', 'onboarding_checklists', 'workstreams', 'documents', 'document_versions',
        'document_reviews', 'document_shares', 'document_grants', 'access_requests', 'change_log', 'onboarding_tasks',
        'notifications', 'audit_logs', 'alert_recipients', 'alert_log']
    loop
        execute format('alter table public.%I enable row level security', t);
        execute format('revoke all on public.%I from anon, authenticated', t);
    end loop;
end $$;
