    id                           integer generated by default as identity primary key,
    repo_category                varchar(5),                     -- CM | POL | RES | PPD | CDP | AGR
    year                         integer,                        -- year of submission (part of the document code)
    serial                       integer,                        -- running number per category + year
    access_level                 varchar(20) default 'internal', -- internal | pilot_shared | role_specific | restricted | public | request_only
