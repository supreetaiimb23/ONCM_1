-- =====================================================================================================================
-- ONCM Workbench - full Supabase (PostgreSQL) schema
-- Run once in: Supabase Dashboard > SQL Editor > New query > paste > Run.
-- Mirrors app/models.py exactly (table + column names), so the FastAPI app works against it without changes.
-- Safe to re-run: every statement is idempotent.
--
-- Access model: the app talks to Postgres directly with the DATABASE_URL role (postgres), which bypasses RLS.
-- RLS is switched ON for every table with NO policies, so the public Supabase REST/GraphQL API (anon / authenticated keys)
-- can read or write nothing. Never put the service-role key or DB password in the browser.
-- =====================================================================================================================

-- ---------------------------------------------------------------------------------------------------------------------
-- 1. Core: users and organisations (profiles <-> organizations reference each other, so FKs are added afterwards)
-- ---------------------------------------------------------------------------------------------------------------------
create table if not exists public.profiles (
    id               integer generated by default as identity primary key,
    email            varchar(255) not null,
    name             varchar(255) not null,
    password_hash    varchar(255),
    role             varchar(30)  not null,                      -- master_admin | secondary_admin | participant
    is_active        boolean      default true,
    organization_id  integer,
    can_share        boolean      default false,                 -- Secondary Admin: may authorise external sharing
    can_export       boolean      default false,                 -- Secondary Admin: may export Excel reports
    repo_access      jsonb,                                      -- admin: repository category codes they may open (null = defaults)
    created_at       timestamptz  default now(),
    constraint profiles_role_chk check (role in ('master_admin', 'secondary_admin', 'participant'))
);
create unique index if not exists ix_profiles_email on public.profiles (email);
create unique index if not exists ux_profiles_email_lower on public.profiles (lower(email));
create index if not exists ix_profiles_role on public.profiles (role);

create table if not exists public.organizations (
    id                 integer generated by default as identity primary key,
    name               varchar(255) not null,
    actor_type         varchar(60)  not null,                    -- Project Developer | VVB | Obligated Entity | ACVA | TSP
    contact_name       varchar(255),
    contact_email      varchar(255),
    intended_role      varchar(255),
    status             varchar(20)  default 'active',            -- active | suspended
    stage              varchar(30)  default 'joined',            -- joined | documents_in_progress | agreement_signed | implementing | live
    waiting_on         varchar(20)  default 'participant',       -- participant | oncm
    assigned_admin_id  integer,
    created_at         timestamptz  default now(),
    updated_at         timestamptz  default now(),
    constraint organizations_status_chk check (status in ('active', 'suspended')),
    constraint organizations_stage_chk  check (stage in ('joined', 'documents_in_progress', 'agreement_signed', 'implementing', 'live'))
);
create index if not exists ix_organizations_name on public.organizations (name);

do $$ begin
    if not exists (select 1 from pg_constraint where conname = 'profiles_organization_id_fkey') then
        alter table public.profiles add constraint profiles_organization_id_fkey
            foreign key (organization_id) references public.organizations (id);
    end if;
    if not exists (select 1 from pg_constraint where conname = 'organizations_assigned_admin_id_fkey') then
        alter table public.organizations add constraint organizations_assigned_admin_id_fkey
            foreign key (assigned_admin_id) references public.profiles (id);
    end if;
end $$;

-- ---------------------------------------------------------------------------------------------------------------------
-- 2. Request to join  (form: "Organizational Profile and Scale")
--    Q1 -> org_name, Q2 -> org_type ... Q17 -> website. Contact fields are used to send the workspace invitation.
-- ---------------------------------------------------------------------------------------------------------------------
create table if not exists public.join_requests (
    id                     integer generated by default as identity primary key,
    -- Q1
    org_name               varchar(255) not null,                -- Full legal name of the organization
    actor_type             varchar(60)  not null,                -- ONCM role applied for
    contact_name           varchar(255) not null,
    contact_email          varchar(255) not null,
    intended_role          varchar(255),
    evidence               text,                                 -- copy of org_profile (kept so older admin screens still work)
    status                 varchar(20)  default 'pending',       -- pending | approved | rejected | more_info
    reason                 text,                                 -- message sent to the applicant with the decision
    duplicate_flag         boolean      default false,
    reviewer_id            integer references public.profiles (id),
    organization_id        integer references public.organizations (id),
    created_at             timestamptz  default now(),
    decided_at             timestamptz,
    -- Q2 - Q9  registration details
    org_type               varchar(40),                          -- Q2
    registration_number    varchar(100),                         -- Q3  CIN / LLPIN / equivalent
    date_of_incorporation  date,                                 -- Q4
    country                varchar(100),                         -- Q5
    state_ut               varchar(100),                         -- Q6
    city                   varchar(100),                         -- Q7
    year_established       integer,                              -- Q8
    registered_address     text,                                 -- Q9
    -- Q10 - Q12  scale and reach
    employee_range         varchar(20),                          -- Q10
    geographic_presence    jsonb,                                -- Q11  array of text
    beneficiary_segments   jsonb,                                -- Q12  array of text
    -- Q13 - Q15  carbon market experience
    standards_worked_with  jsonb,                                -- Q13  array of text (optional)
    certifications         text,                                 -- Q14  (optional)
    carbon_services        jsonb,                                -- Q15  array of text
    -- Q16 - Q17
    org_profile            text,                                 -- Q16  max 150 words
    website                varchar(300),                         -- Q17  (optional)
    -- contact extras
    contact_phone          varchar(40),
    contact_designation    varchar(120),

    constraint join_status_chk   check (status in ('pending', 'approved', 'rejected', 'more_info')),
    constraint join_org_type_chk check (org_type is null or org_type in (
        'Private Limited Company', 'Public Limited Company', 'LLP', 'Partnership', 'Proprietorship', 'Trust', 'Society',
        'Section 8 Company', 'Government body', 'Academic/ Research institution', 'NGO/ Non-Profit', 'FPO/ Cooperative')),
    constraint join_employee_chk check (employee_range is null or employee_range in
        ('1-10', '11-50', '51-200', '201-500', '501-1000', 'More than 1000')),
    constraint join_year_chk     check (year_established is null or year_established >= 1800),   -- 'not in the future' is enforced by the API
    constraint join_doi_chk      check (date_of_incorporation is null or date_of_incorporation >= date '1800-01-01'),   -- 'not in the future' is enforced by the API
    constraint join_geo_chk      check (geographic_presence   is null or (jsonb_typeof(geographic_presence)   = 'array' and geographic_presence   <@ '["Pan-India","South India","West India","North India","East India","Northeast India","Southeast Asia","European Economic region","North America","South America","Africa","Australia"]'::jsonb)),
    constraint join_segments_chk check (beneficiary_segments is null or (jsonb_typeof(beneficiary_segments) = 'array' and beneficiary_segments <@ '["Smallholder farmers","FPOs","Forest Dependent communities","Industry","Corporates","Government","Investors","Project developers","Project / Resource owner"]'::jsonb)),
    constraint join_standards_chk check (standards_worked_with is null or (jsonb_typeof(standards_worked_with) = 'array' and standards_worked_with <@ '["ICM","Gold Standard","GCC","Verra Standard","Plan Vivo","Isometric","RenewCred"]'::jsonb)),
    constraint join_services_chk check (carbon_services is null or (jsonb_typeof(carbon_services) = 'array' and carbon_services <@ '["Project development","MRV/dMRV","Validation","Verification","Registry services","Trading","Advisory","Technology","Finance","Capacity building"]'::jsonb)),
    constraint join_profile_words_chk check (org_profile is null or coalesce(array_length(regexp_split_to_array(btrim(org_profile), '\s+'), 1), 0) <= 150),
    constraint join_website_chk  check (website is null or website = '' or website ~* '^https?://')
);
create index if not exists ix_join_requests_status       on public.join_requests (status, created_at desc);
create index if not exists ix_join_requests_email        on public.join_requests (lower(contact_email));
create index if not exists ix_join_requests_reg_number   on public.join_requests (lower(registration_number));
create index if not exists ix_join_requests_org_name     on public.join_requests (lower(org_name));

